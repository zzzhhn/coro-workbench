"""Evaluate frozen note decoders on explicitly declared Vocadito pilot or holdout.

No new inference, parameters or tempo estimation; holdout requires --holdout and a new explicit protocol. Predictions are
written before the independent checker is invoked with human references.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import time

import librosa
import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from server.lead_note_proposal import CONFIG, decode_lead_note_proposal, frame_acoustic_evidence
from server.vocal import decode_vocal_contour
from server.vocal_dp import decode_duration_contour

PRIVATE = ROOT / 'data/phase4/vocadito-decoders'
OUTPUT = ROOT / 'evidence/phase4/vocadito-decoders.json'
HOLDOUT = False
PROTOCOL_PATH = ROOT / 'evidence/phase4/vocadito-protocol.json'
BENCHMARK_PATH = ROOT / 'data/benchmarks/vocadito/manifest.json'
FCPE_MANIFEST_PATH = ROOT / 'data/phase4/vocadito-pilot/fcpe/manifest.json'


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')


def generate():
    protocol_path = PROTOCOL_PATH
    benchmark_path = BENCHMARK_PATH
    protocol = json.loads(protocol_path.read_text())
    benchmark = json.loads(benchmark_path.read_text())
    prior = json.loads((ROOT / 'evidence/phase3/lead-note-evaluation.json').read_text())
    frozen = {name: sha(ROOT / name) for name in ('server/lead_note_proposal.py', 'server/vocal.py', 'server/vocal_dp.py')}
    assert all(value == prior['sourceCodeSha256'][name] for name, value in frozen.items()), 'Existing profiles changed since frozen experiment'
    assert asdict(CONFIG) == prior['frozenConfig']
    if HOLDOUT:
        ids = next((protocol[key] for key in ('evaluationIds', 'holdoutIds', 'heldoutIds') if key in protocol), None)
        if not isinstance(ids, list) or len(ids) != 32 or len(set(ids)) != 32:
            raise ValueError('Holdout requires a new explicit32-ID protocol evaluationIds/holdoutIds/heldoutIds; old reservedIds alone never unlock scoring')
        assert set(ids) == set(benchmark['reservedIds']) and not set(ids) & set(benchmark['pilotIds'])
        assert set(protocol['models']) == {'standard', 'acoustic_segments'} and protocol['parameterChanges'] is False
        assert all(sha(ROOT / name) == value for name, value in protocol['sourceSha256'].items()), 'New protocol frozen module hashes changed'
    else:
        ids = protocol['pilotIds']
        assert ids == ['1', '10', '11', '12', '13', '14', '15', '16'] == benchmark['pilotIds']
    tracks = {entry['id']: entry for entry in benchmark['tracks'] if entry['id'] in ids}
    source_manifest_path = FCPE_MANIFEST_PATH
    source_manifest = json.loads(source_manifest_path.read_text())
    source_rows = {row['id']: row for row in source_manifest['rows']}
    assert set(source_rows) == set(ids)
    if not HOLDOUT:
        assert source_manifest['pilotIds'] == ids
    profiles = ('standard', 'acoustic_segments') if HOLDOUT else ('standard', 'legato', 'acoustic_segments')
    private_manifest = {'models': {name: {} for name in profiles}}
    generation = {'sourceSha256': frozen, 'runnerSha256': sha(Path(__file__)), 'protocolSha256': sha(protocol_path), 'benchmarkManifestSha256': sha(benchmark_path), 'fcpeManifestSha256': sha(source_manifest_path), 'frozenConfig': asdict(CONFIG), 'evaluationIds': ids, 'split': 'holdout32' if HOLDOUT else 'pilot8', 'profilesScored': list(profiles), 'otherSplitState': 'Original8 pilot references/audio not opened by holdout mode' if HOLDOUT else 'Not opened, decoded or scored by this task; only manifest/protocol partition metadata read', 'neuralInference': False, 'defaultsChanged': False, 'profileEligibility': {'standard': 'Existing saved default baseline, regenerated byte-comparable events', 'legato': 'Existing decoder, minimum100ms / transitionPenalty2, no changed parameters', 'acoustic_segments': 'Existing frozen configuration, no changed parameters', 'metric_boundary': {'status': 'not_scored_missing_authoritative_grid', 'requires': 'Finite20..300 BPM and beat phase', 'reason': 'No independent BPM/phase supplied in the pilot manifest. Arbitrary fixed BPM or reference-derived tempo would not be a fair comparison; no tempo estimation or new inference performed.'}}, 'rows': []}
    PRIVATE.mkdir(parents=True, exist_ok=True)
    for identifier in ids:
        entry = tracks[identifier]
        assert (identifier in benchmark['reservedIds']) if HOLDOUT else entry['split'] == 'pilot'
        audio_path = Path(benchmark['datasetRoot']) / entry['audio']
        contour_path = ROOT / source_rows[identifier]['contour']
        baseline_path = ROOT / source_rows[identifier]['notes']
        hashes = {'audio': sha(audio_path), 'contour': sha(contour_path), 'savedBaselineNotes': sha(baseline_path)}
        assert hashes['audio'] == source_rows[identifier]['audioSha256']
        assert hashes['contour'] == source_rows[identifier]['contourSha256']
        with np.load(contour_path, allow_pickle=False) as arrays:
            times, f0, activation = (arrays[key].copy() for key in ('time', 'f0', 'activation'))
        audio, sr = sf.read(audio_path, dtype='float32', always_2d=True)
        y = audio.mean(axis=1)
        if sr != 16000:
            y = librosa.resample(y, orig_sr=sr, target_sr=16000)
        y = (y / max(1., np.max(np.abs(y)))).astype(np.float32)
        sr = 16000
        evidence = frame_acoustic_evidence(times, y, sr)
        target = PRIVATE / identifier
        target.mkdir(exist_ok=True)
        np.savez_compressed(target / 'acoustic-evidence.npz', **evidence)
        results = {}
        started = time.monotonic()
        events, details = decode_vocal_contour(times, f0, activation, y, sr)
        old_events = json.loads(baseline_path.read_text())['events']
        assert events == old_events, f'{identifier}: regenerated baseline differs from saved prediction'
        results['standard'] = (events, details)
        if 'legato' in profiles:
            results['legato'] = decode_duration_contour(times, f0, activation, y, sr, 'legato')
        results['acoustic_segments'] = decode_lead_note_proposal(times, f0, activation, y, sr, profile='acoustic_segments', acoustic_evidence=evidence)
        for profile, (events, details) in results.items():
            path = target / f'{profile}-notes.json'
            save(path, {'pitchUnit': 'midi', 'events': events, 'decoder': details, 'decodeVariant': profile, 'sameFcpeF0': True})
            private_manifest['models'][profile][identifier] = {'f0': str(contour_path), 'notes': str(path)}
        assert hashes == {'audio': sha(audio_path), 'contour': sha(contour_path), 'savedBaselineNotes': sha(baseline_path)}
        row = {'id': identifier, 'inputSha256': hashes, 'eventCounts': {profile: len(value[0]) for profile, value in results.items()}, 'predictionSha256': {profile: sha(target / f'{profile}-notes.json') for profile in results}, 'baselineEventsEqualSaved': True, 'decodeSeconds': round(time.monotonic() - started, 5)}
        generation['rows'].append(row)
        print(json.dumps(row), flush=True)
    assert all(sha(ROOT / name) == value for name, value in frozen.items())
    save(PRIVATE / 'predictions.json', private_manifest)
    save(PRIVATE / 'generation.json', generation)
    return generation


def score(generation):
    evaluator_path = ROOT / 'scripts/evaluate-vocal-groundtruth.py'
    # The scorer is independent of all decoder implementation and receives only files.
    command = [sys.executable, str(evaluator_path), '--predictions-manifest', str(PRIVATE / 'predictions.json'), '--output', str(PRIVATE / 'checker-summary.json'), '--private-output', str(PRIVATE / 'checker-private')]
    if HOLDOUT:
        command += ['--holdout', '--protocol', str(PROTOCOL_PATH), '--benchmark-manifest', str(BENCHMARK_PATH)]
    completed = subprocess.run(command, capture_output=True, text=True, check=True)
    (PRIVATE / 'checker-stdout.txt').write_text(completed.stdout)
    report = json.loads((PRIVATE / 'checker-summary.json').read_text())
    crosschecks = []
    import mir_eval
    for profile, model in report['models'].items():
        for row in model['rows']:
            identifier = row['id']
            notes = json.loads((PRIVATE / identifier / f'{profile}-notes.json').read_text())['events']
            events = np.asarray(notes, dtype=float).reshape(-1, 4)
            intervals, pitches = events[:, :2], 440 * 2 ** ((events[:, 2] - 69) / 12)
            for annotator in ('A1', 'A2'):
                reference = np.loadtxt(ROOT / f'data/benchmarks/vocadito/Annotations/Notes/vocadito_{identifier}_notes{annotator}.csv', delimiter=',')
                ref_intervals = np.column_stack([reference[:, 0], reference[:, 0] + reference[:, 2]])
                for mode, ratio in [('onsetPitch', None), ('onsetOffsetPitch', .2)]:
                    matches = mir_eval.transcription.match_notes(ref_intervals, reference[:, 1], intervals, pitches, offset_ratio=ratio)
                    metric = row['notes'][annotator][mode]
                    assert len(matches) == metric['matchedNotes'], (profile, identifier, annotator, mode)
                    metric['falsePositiveNotes'] = metric['estimatedNotes'] - metric['matchedNotes']
                    metric['falseNegativeNotes'] = metric['referenceNotes'] - metric['matchedNotes']
                    if matches:
                        pairs = np.asarray(matches)
                        onset = np.abs(ref_intervals[pairs[:, 0], 0] - intervals[pairs[:, 1], 0])
                        offset = np.abs(ref_intervals[pairs[:, 0], 1] - intervals[pairs[:, 1], 1])
                        metric['medianAbsoluteOnsetErrorSecondsMatchedOnly'] = float(np.median(onset))
                        metric['medianAbsoluteOffsetErrorSecondsMatchedOnly'] = float(np.median(offset))
                    crosschecks.append({'profile': profile, 'id': identifier, 'annotator': annotator, 'mode': mode, 'matchedCountsEqual': True})
        for annotator, modes in model['aggregate']['notes'].items():
            for mode, value in modes.items():
                value['falsePositiveNotes'] = value['estimatedNotes'] - value['matchedNotes']
                value['falseNegativeNotes'] = value['referenceNotes'] - value['matchedNotes']
    if HOLDOUT:
        protocol = json.loads(PROTOCOL_PATH.read_text())
        limits = protocol['promotionEvidenceGate']
        checks = {}
        for annotator in ('A1', 'A2'):
            base = report['models']['standard']['aggregate']['notes'][annotator]['onsetOffsetPitch']
            new = report['models']['acoustic_segments']['aggregate']['notes'][annotator]['onsetOffsetPitch']
            before = {row['id']: row['notes'][annotator]['onsetOffsetPitch']['f1'] for row in report['models']['standard']['rows']}
            deltas = {row['id']: row['notes'][annotator]['onsetOffsetPitch']['f1'] - before[row['id']] for row in report['models']['acoustic_segments']['rows']}
            losses = {identifier: delta for identifier, delta in deltas.items() if delta < -.05 - 1e-12}
            macro_delta = new['macroF1'] - base['macroF1']
            micro_delta = new['microF1'] - base['microF1']
            checks[annotator] = {'macroF1Delta': macro_delta, 'microF1Delta': micro_delta, 'perTrackDelta': deltas, 'tracksLosingOverPoint05': losses, 'passes': macro_delta >= limits['minimumMacroImprovementEachAnnotator'] - 1e-12 and micro_delta > 0 and len(losses) <= limits['maximumTracksWithF1LossOverPoint05EachAnnotator']}
        report['predeclaredBenchmarkGate'] = {'limits': limits, 'annotators': checks, 'passesBenchmarkOnly': all(value['passes'] for value in checks.values()), 'finalAcceptance': False}
    report['decoderGeneration'] = generation
    report['metricBoundaryStatus'] = generation['profileEligibility']['metric_boundary']
    report['mirEvalCrosscheck'] = {'version': mir_eval.__version__, 'comparedCounts': len(crosschecks), 'allEqual': True}
    report['predictionPolicy'] = 'All predictions generated from identical existing FCPE contours/audio before scorer opened human notes. All F0 scores are identical because this is note-decoder comparison only.'
    report['scope'] = ('Explicit32-track locked holdout; standard/acoustic_segments only; original8 pilot data untouched.' if HOLDOUT else 'Eight fixed human-reviewed unaccompanied pilot recordings only; no reserved32 access.') + ' Two annotators separate. Existing frozen decoders; no reference-driven parameters, neural inference or default change.'
    save(OUTPUT, report)
    print(json.dumps({profile: model['aggregate']['notes'] for profile, model in report['models'].items()}, indent=2), flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--holdout', action='store_true', help='Requires separately predeclared32-ID protocol; never uses old reservedIds alone')
    parser.add_argument('--protocol', type=Path)
    parser.add_argument('--fcpe-manifest', type=Path)
    parser.add_argument('--benchmark-manifest', type=Path, default=BENCHMARK_PATH)
    parser.add_argument('--private-output', type=Path)
    parser.add_argument('--output', type=Path)
    stages = parser.add_mutually_exclusive_group()
    stages.add_argument('--generate-only', action='store_true', help='Freeze predictions without opening human annotations')
    stages.add_argument('--score-only', action='store_true', help='Score an existing prediction manifest without regenerating notes')
    args = parser.parse_args()
    HOLDOUT = args.holdout
    BENCHMARK_PATH = args.benchmark_manifest.resolve()
    if HOLDOUT:
        PROTOCOL_PATH = (args.protocol or ROOT / 'evidence/phase4/vocadito-holdout-protocol.json').resolve()
        FCPE_MANIFEST_PATH = (args.fcpe_manifest or ROOT / 'data/phase4/vocadito-holdout/fcpe/manifest.json').resolve()
        PRIVATE = (args.private_output or ROOT / 'data/phase4/vocadito-holdout-decoders').resolve()
        OUTPUT = (args.output or ROOT / 'evidence/phase4/vocadito-holdout-decoders.json').resolve()
        pilot_private = (ROOT / 'data/phase4/vocadito-decoders').resolve()
        assert not PRIVATE.is_relative_to(pilot_private) and not pilot_private.is_relative_to(PRIVATE), 'Holdout must use a distinct private directory'
        assert OUTPUT != (ROOT / 'evidence/phase4/vocadito-decoders.json').resolve(), 'Never overwrite pilot summary'
    else:
        PROTOCOL_PATH = (args.protocol or PROTOCOL_PATH).resolve()
        FCPE_MANIFEST_PATH = (args.fcpe_manifest or FCPE_MANIFEST_PATH).resolve()
        PRIVATE = (args.private_output or PRIVATE).resolve()
        OUTPUT = (args.output or OUTPUT).resolve()
    if OUTPUT.exists() or ((PRIVATE / 'predictions.json').exists() and not args.score_only):
        raise FileExistsError('Evidence is frozen; choose new explicit output paths rather than overwrite prior predictions/report')
    assert PRIVATE.is_relative_to(ROOT / 'data'), 'Detailed outputs must stay under ignored data/'
    if args.score_only:
        generation = json.loads((PRIVATE / 'generation.json').read_text())
        assert generation['runnerSha256'] == sha(Path(__file__)) and generation['protocolSha256'] == sha(PROTOCOL_PATH)
        assert generation['fcpeManifestSha256'] == sha(FCPE_MANIFEST_PATH)
        assert all(sha(ROOT / name) == value for name, value in generation['sourceSha256'].items())
    else:
        generation = generate()
    if not args.generate_only:
        score(generation)
